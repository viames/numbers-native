import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { NumbersBridge } from '../plugins/numbers-native/src/bridge.mjs';
import { NumbersTools } from '../plugins/numbers-native/src/tools.mjs';

const folder = mkdtempSync(join(tmpdir(), 'numbers-native-advanced-'));
const service = new NumbersTools(new NumbersBridge(), { roots: [folder] });
const run = (name, args = {}) => service.execute(`numbers_${name}`, args);
const checks = [];
let id;
try {
  const doc = await run('create', { path: join(folder, 'Template chart.numbers'), template_id: 'Application/21_Table_and_Chart/Traditional' });
  id = doc.document_id;
  const d = { document_id: id }, s = { ...d, sheet: 1 };
  const charts = (await run('objects', s)).objects.filter(x => x.kind === 'chart');
  assert.ok(charts.length); checks.push('Create document with existing native chart from template');
  const original = charts[0];
  const moved = await run('object', { ...s, kind: 'chart', object: original.index, action: 'update', x: original.position.x + 10, width: original.width + 20 });
  const changed = moved.objects.find(x => x.kind === 'chart' && x.index === original.index);
  assert.equal(changed.position.x, original.position.x + 10); assert.equal(changed.width, original.width + 20);
  checks.push('Inspect/move/resize native chart');
  await run('table', { ...s, action: 'create', name: 'Source', rows: 5, columns: 3, header_rows: 0, header_columns: 0 });
  await run('table', { ...s, action: 'create', name: 'Results', rows: 5, columns: 3, header_rows: 0, header_columns: 0 });
  await run('write', { ...s, table: 'Source', start: 'B2', values: [[21]] });
  assert.equal((await run('write', { ...s, table: 'Results', start: 'A1', values: [[{ formula: '=Source::B2*2' }]] })).cells[0][0].value, 42);
  checks.push('Cross-table formula evaluated by Numbers');
  const dims = await run('dimensions', { ...s, table: 'Source', axis: 'row', first: 1, last: 1, size: 35 });
  assert.equal(dims.sizes[0], 35); checks.push('Dimension changes verified through native readback');
  const literal = await run('write', { ...s, table: 'Source', start: 'A1', values: [['001']] });
  const cleared = await run('write', { ...s, table: 'Source', start: 'A1', values: [[null]] });
  assert.equal(literal.cells[0][0].format, 'text'); assert.equal(cleared.cells[0][0].format, 'text'); assert.equal(cleared.cells[0][0].value, null);
  checks.push('Null write preserves literal-text format');
  await run('write', { ...s, table: 'Source', start: 'A1', values: [['001']] });
  const numeric = await run('write', { ...s, table: 'Source', start: 'A1', values: [[7]] });
  assert.equal(numeric.cells[0][0].value, 7);
  await run('format', { ...s, table: 'Source', range: 'A1', format: 'currency' });
  const formula = await run('write', { ...s, table: 'Source', start: 'A1', values: [[{ formula: '=3*4' }]] });
  assert.equal(formula.cells[0][0].value, 12); assert.equal(formula.cells[0][0].format, 'currency');
  await run('format', { ...s, table: 'Source', range: 'A1', format: 'number' });
  assert.equal((await run('read', { ...s, table: 'Source', range: 'A1' })).cells[0][0].format, 'number');
  checks.push('Replace literal text with numbers, preserve currency on formula edits and read numeric format');
  await assert.rejects(run('read', { ...s, table: 'Source', range: 'A1:Z1' }), e => e.code === 'RANGE_OUT_OF_BOUNDS');
  await assert.rejects(run('sheet', { ...d, action: 'delete', sheet: 1 }), e => e.code === 'LAST_SHEET');
  checks.push('Out-of-bounds and final-sheet guards');
  const visible = (await run('documents')).documents;
  assert.ok(visible.some(x => x.document_id === id)); assert.ok(visible.every(x => x.path.includes('numbers-native-advanced-')));
  checks.push('Allowed roots filter open-document metadata');
  const result = { passed: true, checks };
  if (process.env.NUMBERS_NATIVE_ADVANCED_EVIDENCE) writeFileSync(process.env.NUMBERS_NATIVE_ADVANCED_EVIDENCE, JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { if (id) await run('close', { document_id: id }); }
